# Bakes Japanese sign lettering from Noto Sans JP Bold into js/data/glyphs.js so signs show real
# kanji/kana on any PC (no font needed at runtime). Each glyph = list of merged rectangles on a
# 24x24 grid, each rect encoded as 4 chars chr(48+v): x, y(from top), w, h.
import json
from PIL import Image, ImageDraw, ImageFont

PX = 24
FONT = '/usr/share/fonts/google-noto-cjk/NotoSansJP-Bold.otf'

# Shop signs read top-to-bottom (tategaki). Generic shop types + real Shinjuku place names, no brands.
SIGNS_V = ['居酒屋', 'カラオケ', 'ラーメン', '焼肉', '寿司', '薬局', 'ホテル', 'パチンコ', '麻雀', '喫茶',
           '酒場', '餃子', '牛丼', '定食', '焼鳥', 'うどん', '天ぷら', '漫画喫茶', '質屋', '歯科', '英会話',
           '不動産', '二十四時間', '営業中', '飲み放題', '整体', '古着', '中華料理', '立ち飲み', 'バー', '占い',
           '美容室', '書店', '純喫茶', '串カツ', 'もつ焼', 'ゲーム', '大衆酒場', '生ビール', '鮨', '炉端焼',
           'そば', 'カレー', '銭湯', 'スナック', '焼酎', '黒ホッピー', '洋食', 'とんかつ', 'ビリヤード']
# Wide signs on rooftops, awnings and the big screens.
SIGNS_H = ['新宿', '歌舞伎町一番街', '思い出横丁', '東口', '西口', '大ガード', 'カラオケ', 'ゲームセンター',
           'ドラッグストア', '居酒屋', '24時間営業', 'ラーメン', '焼肉', '飲み放題', '駐車場', 'コインパーキング',
           '新宿駅', 'タクシー乗り場', '日の出運送', 'OPEN', 'HOTEL', 'BAR', 'KARAOKE', '24H']
# Short words on red paper lanterns.
LANTERN = ['焼鳥', '酒', 'おでん', '祭', '食堂', 'もつ', '串', '生']
# Station / street name plates.
PLATES = ['新宿三丁目', '歌舞伎町', '靖国通り', '新宿通り', '明治通り', '青梅街道', '止まれ', '日の出マート', '交番', 'タバコ', '渋谷', '池袋']

chars = sorted(set(''.join(SIGNS_V + SIGNS_H + LANTERN + PLATES)))
font = ImageFont.truetype(FONT, 22)

def rects_of(ch):
    im = Image.new('L', (PX, PX), 0)
    d = ImageDraw.Draw(im)
    l, t, r, b = d.textbbox((0, 0), ch, font=font)
    w, h = r - l, b - t
    # Centre the ink box in the cell; kana/kanji fill it, latin is narrower.
    d.text(((PX - w) / 2 - l, (PX - h) / 2 - t), ch, font=font, fill=255)
    px = im.load()
    on = [[px[x, y] > 110 for x in range(PX)] for y in range(PX)]
    used = [[False] * PX for _ in range(PX)]
    out = []
    for y in range(PX):
        x = 0
        while x < PX:
            if on[y][x] and not used[y][x]:
                x1 = x
                while x1 + 1 < PX and on[y][x1 + 1] and not used[y][x1 + 1]:
                    x1 += 1
                hh = 1
                while y + hh < PX and all(on[y + hh][k] and not used[y + hh][k] for k in range(x, x1 + 1)):
                    hh += 1
                for yy in range(y, y + hh):
                    for k in range(x, x1 + 1):
                        used[yy][k] = True
                out.append((x, y, x1 - x + 1, hh))
                x = x1 + 1
            else:
                x += 1
    return out, w

glyphs, adv, total = {}, {}, 0
for ch in chars:
    rs, w = rects_of(ch)
    total += len(rs)
    glyphs[ch] = ''.join(chr(48 + v) for r in rs for v in r)
    if ord(ch) < 128:
        adv[ch] = max(8, w + 3)

bad = [c for c, s in glyphs.items() if not s]
assert not bad, 'empty glyphs: ' + ''.join(bad)
for s in glyphs.values():
    assert '\\' not in s and "'" not in s and '`' not in s

j = lambda o: json.dumps(o, ensure_ascii=False)
src = (
    '// GENERATED by tests/bake_glyphs.py from Noto Sans JP Bold (SIL Open Font License). Do not edit.\n'
    '// Each glyph is a list of rectangles on a %dx%d grid: 4 chars per rect, value = charCode - 48 (x, y from top, w, h).\n' % (PX, PX)
    + 'export const GLYPH_PX = %d;\n' % PX
    + 'export const GLYPHS = ' + j(glyphs) + ';\n'
    + 'export const ADVANCE = ' + j(adv) + ';\n'
    + 'export const SIGNS_V = ' + j(SIGNS_V) + ';\n'
    + 'export const SIGNS_H = ' + j(SIGNS_H) + ';\n'
    + 'export const LANTERN = ' + j(LANTERN) + ';\n'
    + 'export const PLATES = ' + j(PLATES) + ';\n'
)
open('/data/hinode/js/data/glyphs.js', 'w', encoding='utf-8').write(src)
print('glyphs', len(chars), 'rects', total, 'avg', round(total / len(chars), 1), 'bytes', len(src.encode('utf-8')))
